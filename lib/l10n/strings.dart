extension Tr on BuildContext {
  bool get isTelugu => AppScope.of(this).isTelugu;

  /// Translated string for [key]; `{x}` placeholders are filled from [args].
  String tr(String key, [Map<String, String> args = const {}]) {
    var s = (isTelugu ? _te[key] : null) ?? _en[key] ?? key;
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }
}

