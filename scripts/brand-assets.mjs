#!/usr/bin/env node
// Generates every logo-derived asset from the official artwork in brand/VW.png.
// The artwork itself is never redrawn: we only crop surrounding whitespace,
// make edge-connected background transparent, and scale without distortion.
//
// Outputs
//   public/brand/votewala-logo.png              tight crop, original background
//   public/brand/votewala-logo-transparent.png  tight crop, transparent background
//   public/brand/votewala-mark.png              symbol crop (V/W + ballot box), 512px square
//   public/brand/icon-192.png, icon-512.png, icon-maskable-512.png
//   src/app/favicon.ico, src/app/icon.png, src/app/apple-icon.png
//   src/styles/brand-meta.json                  dimensions + sampled colours
//   src/styles/brand-tokens.css                 brand colour tokens sampled from the logo
//
// Usage: node scripts/brand-assets.mjs [--strict]
//   --strict  fail when brand/VW.png is missing (used by `npm run build`)
//
// If the automatic symbol detection picks the wrong region, add
// brand/crop.json: { "left": 0, "top": 0, "width": 400, "height": 400 }
// with coordinates in the original VW.png.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";
import pngToIco from "png-to-ico";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const strict = process.argv.includes("--strict");
const SOURCE_CANDIDATES = ["brand/VW.png", "brand/vw.png", "brand/VW.PNG"];
const out = (p) => path.join(root, p);

const DEFAULT_TOKENS = {
  orange: [0xf3, 0x6c, 0x13],
  green: [0x15, 0x94, 0x47],
  navy: [0x14, 0x23, 0x3d],
};

function writeTokens(colours, sampled) {
  const ink = (rgb) => darkenToContrast(rgb, 4.6);
  const v = (rgb) => rgb.join(" ");
  const css = `/* Generated by scripts/brand-assets.mjs — do not edit by hand.
 * ${sampled ? "Colours sampled from brand/VW.png." : "Default tokens (brand/VW.png not found yet)."}
 * *-ink variants are the same hue darkened to >= 4.5:1 contrast on white,
 * used for text and for white-on-colour buttons. */
:root {
  --brand-orange: ${v(colours.orange)}; /* ${hex(colours.orange)} */
  --brand-orange-ink: ${v(ink(colours.orange))}; /* ${hex(ink(colours.orange))} */
  --brand-green: ${v(colours.green)}; /* ${hex(colours.green)} */
  --brand-green-ink: ${v(ink(colours.green))}; /* ${hex(ink(colours.green))} */
  --brand-navy: ${v(colours.navy)}; /* ${hex(colours.navy)} */
}
`;
  mkdirSync(out("src/styles"), { recursive: true });
  writeFileSync(out("src/styles/brand-tokens.css"), css);
}

function writeMeta(meta) {
  mkdirSync(out("src/styles"), { recursive: true });
  writeFileSync(out("src/styles/brand-meta.json"), JSON.stringify(meta, null, 2) + "\n");
}

// ---------- colour helpers ----------
const hex = (rgb) => "#" + rgb.map((c) => c.toString(16).padStart(2, "0")).join("").toUpperCase();
function luminance([r, g, b]) {
  const f = (c) => {
    c /= 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}
const contrastWithWhite = (rgb) => 1.05 / (luminance(rgb) + 0.05);
function darkenToContrast(rgb, target) {
  let c = [...rgb];
  for (let i = 0; i < 100 && contrastWithWhite(c) < target; i++) c = c.map((x) => Math.max(0, Math.round(x * 0.97)));
  return c;
}
function rgbToHsl(r, g, b) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min;
  const s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  let h;
  if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
  else if (max === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;
  return [h * 60, s, l];
}

// ---------- main ----------
const sourceRel = SOURCE_CANDIDATES.find((p) => existsSync(out(p)));
if (!sourceRel) {
  const msg = "brand/VW.png not found. Copy the official VoteWala logo to brand/VW.png and re-run `npm run brand`.";
  if (strict) {
    console.error(`✖ ${msg}`);
    process.exit(1);
  }
  console.warn(`⚠ ${msg}`);
  if (!existsSync(out("src/styles/brand-tokens.css"))) writeTokens(DEFAULT_TOKENS, false);
  if (!existsSync(out("src/styles/brand-meta.json"))) writeMeta({ present: false });
  process.exit(0);
}

const sourceBuf = readFileSync(out(sourceRel));
const sha256 = createHash("sha256").update(sourceBuf).digest("hex");
const img = sharp(sourceBuf).ensureAlpha();
const { data, info } = await img.raw().toBuffer({ resolveWithObject: true });
const { width: W, height: H } = info;
const px = (x, y) => {
  const i = (y * W + x) * 4;
  return [data[i], data[i + 1], data[i + 2], data[i + 3]];
};

// Background colour = most common corner colour.
const corners = [px(0, 0), px(W - 1, 0), px(0, H - 1), px(W - 1, H - 1)];
const bg = corners.sort(
  (a, b) => corners.filter((c) => dist(c, b) < 30).length - corners.filter((c) => dist(c, a) < 30).length,
)[0];
function dist(a, b) {
  if (a[3] < 16 && b[3] < 16) return 0;
  return Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2], (a[3] - b[3]) * 1.5);
}
const TOL = 28;
const isBg = (x, y) => dist(px(x, y), bg) < TOL;

// Background reachable from the image border (flood fill) — interior areas that
// happen to share the background colour are part of the artwork and are kept.
const outside = new Uint8Array(W * H);
const stack = [];
for (let x = 0; x < W; x++) stack.push(x, 0, x, H - 1);
for (let y = 0; y < H; y++) stack.push(0, y, W - 1, y);
while (stack.length) {
  const y = stack.pop(), x = stack.pop();
  if (x < 0 || y < 0 || x >= W || y >= H) continue;
  const k = y * W + x;
  if (outside[k] || !isBg(x, y)) continue;
  outside[k] = 1;
  stack.push(x + 1, y, x - 1, y, x, y + 1, x, y - 1);
}

// Tight bounding box of the artwork.
let minX = W, minY = H, maxX = -1, maxY = -1;
for (let y = 0; y < H; y++)
  for (let x = 0; x < W; x++)
    if (!outside[y * W + x]) {
      if (x < minX) minX = x;
      if (x > maxX) maxX = x;
      if (y < minY) minY = y;
      if (y > maxY) maxY = y;
    }
if (maxX < 0) {
  console.error("✖ brand/VW.png appears to be empty.");
  process.exit(1);
}
const pad = Math.round(Math.max(maxX - minX, maxY - minY) * 0.02);
const crop = {
  left: Math.max(0, minX - pad),
  top: Math.max(0, minY - pad),
  width: Math.min(W, maxX + pad + 1) - Math.max(0, minX - pad),
  height: Math.min(H, maxY + pad + 1) - Math.max(0, minY - pad),
};

// Transparent derivative: zero alpha only on border-connected background.
const transparent = Buffer.from(data);
for (let k = 0; k < W * H; k++) if (outside[k]) transparent[k * 4 + 3] = 0;
const transparentImg = () => sharp(transparent, { raw: { width: W, height: H, channels: 4 } });

mkdirSync(out("public/brand"), { recursive: true });
await sharp(sourceBuf).extract(crop).png({ compressionLevel: 9 }).toFile(out("public/brand/votewala-logo.png"));
await transparentImg().extract(crop).png({ compressionLevel: 9 }).toFile(out("public/brand/votewala-logo-transparent.png"));

// ---------- symbol detection ----------
function bands(counts, minGap) {
  const groups = [];
  let start = -1, gap = 0;
  counts.forEach((c, i) => {
    if (c > 0) {
      if (start < 0) start = i;
      gap = 0;
    } else if (start >= 0) {
      gap++;
      if (gap >= minGap) {
        groups.push([start, i - gap]);
        start = -1;
        gap = 0;
      }
    }
  });
  if (start >= 0) groups.push([start, counts.length - 1 - gap]);
  return groups;
}
function inkBox(x0, y0, x1, y1) {
  let a = x1, b = y1, c = x0, d = y0;
  for (let y = y0; y <= y1; y++)
    for (let x = x0; x <= x1; x++)
      if (!outside[y * W + x]) {
        a = Math.min(a, x); b = Math.min(b, y); c = Math.max(c, x); d = Math.max(d, y);
      }
  return { left: a, top: b, width: c - a + 1, height: d - b + 1 };
}

let symbol;
const overridePath = out("brand/crop.json");
if (existsSync(overridePath)) {
  symbol = JSON.parse(readFileSync(overridePath, "utf8"));
  console.log("• Using symbol crop from brand/crop.json");
} else {
  const colInk = Array.from({ length: maxX - minX + 1 }, (_, i) => {
    let n = 0;
    for (let y = minY; y <= maxY; y++) n += outside[y * W + minX + i] ? 0 : 1;
    return n;
  });
  const rowInk = Array.from({ length: maxY - minY + 1 }, (_, i) => {
    let n = 0;
    for (let x = minX; x <= maxX; x++) n += outside[(minY + i) * W + x] ? 0 : 1;
    return n;
  });
  const cols = bands(colInk, Math.max(3, Math.round(colInk.length * 0.015)));
  const rows = bands(rowInk, Math.max(3, Math.round(rowInk.length * 0.015)));
  const squareish = (b) => b.width / b.height > 0.55 && b.width / b.height < 1.8;
  const first = (g, horizontal) =>
    horizontal ? inkBox(minX + g[0], minY, minX + g[1], maxY) : inkBox(minX, minY + g[0], maxX, minY + g[1]);
  if (cols.length >= 2 && squareish(first(cols[0], true))) symbol = first(cols[0], true);
  else if (rows.length >= 2 && squareish(first(rows[0], false))) symbol = first(rows[0], false);
  else symbol = { left: minX, top: minY, width: maxX - minX + 1, height: maxY - minY + 1 };
  console.log(`• Symbol region: ${JSON.stringify(symbol)} (override with brand/crop.json if needed)`);
}

const markPng = await transparentImg().extract(symbol).png().toBuffer();
async function square(size, { scale = 1, background = { r: 0, g: 0, b: 0, alpha: 0 } } = {}) {
  const inner = Math.round(size * scale);
  const fitted = await sharp(markPng)
    .resize(inner, inner, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 }, kernel: "lanczos3" })
    .toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background } })
    .composite([{ input: fitted, gravity: "center" }])
    .png()
    .toBuffer();
}
const white = { r: 255, g: 255, b: 255, alpha: 1 };
writeFileSync(out("public/brand/votewala-mark.png"), await square(512));
writeFileSync(out("public/brand/icon-192.png"), await square(192, { scale: 0.86, background: white }));
writeFileSync(out("public/brand/icon-512.png"), await square(512, { scale: 0.86, background: white }));
writeFileSync(out("public/brand/icon-maskable-512.png"), await square(512, { scale: 0.62, background: white }));
writeFileSync(out("src/app/icon.png"), await square(512, { scale: 0.92 }));
writeFileSync(out("src/app/apple-icon.png"), await square(180, { scale: 0.8, background: white }));
writeFileSync(
  out("src/app/favicon.ico"),
  await pngToIco([await square(16), await square(32), await square(48)]),
);

// ---------- colour sampling ----------
const buckets = { orange: new Map(), green: new Map(), navy: new Map() };
for (let y = minY; y <= maxY; y += 1)
  for (let x = minX; x <= maxX; x += 1) {
    const [r, g, b, a] = px(x, y);
    if (a < 250 || outside[y * W + x]) continue;
    const [h, s, l] = rgbToHsl(r, g, b);
    let bucket = null;
    if (h >= 10 && h <= 45 && s > 0.55 && l > 0.3 && l < 0.7) bucket = "orange";
    else if (h >= 85 && h <= 170 && s > 0.35 && l > 0.15 && l < 0.6) bucket = "green";
    else if (h >= 190 && h <= 250 && s > 0.2 && l < 0.32) bucket = "navy";
    if (!bucket) continue;
    const key = `${r},${g},${b}`;
    buckets[bucket].set(key, (buckets[bucket].get(key) ?? 0) + 1);
  }
const sampled = {};
const mode = (m) => {
  let best = null, n = 0;
  for (const [k, v] of m) if (v > n) { best = k; n = v; }
  return n >= 50 ? best.split(",").map(Number) : null;
};
for (const k of Object.keys(buckets)) sampled[k] = mode(buckets[k]);
const colours = {
  orange: sampled.orange ?? DEFAULT_TOKENS.orange,
  green: sampled.green ?? DEFAULT_TOKENS.green,
  navy: sampled.navy ?? DEFAULT_TOKENS.navy,
};
writeTokens(colours, true);
writeMeta({
  present: true,
  source: sourceRel,
  sha256,
  original: { width: W, height: H },
  logo: { width: crop.width, height: crop.height },
  symbol,
  colours: Object.fromEntries(Object.entries(colours).map(([k, v]) => [k, hex(v)])),
  sampled: Object.fromEntries(Object.entries(sampled).map(([k, v]) => [k, v ? hex(v) : null])),
});

console.log(`✔ Brand assets generated from ${sourceRel} (${W}×${H}, crop ${crop.width}×${crop.height})`);
for (const k of Object.keys(colours))
  console.log(`  ${k.padEnd(6)} ${hex(colours[k])}${sampled[k] ? " (sampled from logo)" : " (default — not found in logo)"}`);
