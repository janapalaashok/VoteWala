"""Generates lib/data/external_data.dart from the Facebook data workbook.

    python3 tools/import_external.py tools/data/external_facebook_jan_oct_2026.xlsx

Sheets used: "Constituency Votes" (Month, Constituency, Votes) and
"Featured Polls" (Month, Poll, Option, Votes). Year 2026.
"""
import re
import sys
from pathlib import Path

import openpyxl

YEAR = 2026
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September",
          "October", "November", "December"]
ALIASES = {  # spreadsheet name -> name in lib/data/ap_data.dart
    "Anakapalle": "Anakapalli",
    "Yelamanchili": "Elamanchili",
    "Payakaraopeta": "Payakaraopet",
    "Pulivendula": "Pulivendla",
    "Tadpatri": "Tadipatri",
    "Gannavaram": "P. Gannavaram",
    "Gannavaram (Krishna)": "Gannavaram",
}
POLLS = {"Vote for CM": "cm-2026"}

src = Path("lib/data/ap_data.dart").read_text()
block = src[src.index("const _acRaw"):]
block = block[: block.index("];")]
ac = [s.split("|")[0] for s in re.findall(r"'([^']+)'", block)]
assert len(ac) == 175, len(ac)

wb = openpyxl.load_workbook(sys.argv[1], read_only=True)


def key(month):
    return f"{YEAR}-{MONTHS.index(month.strip()) + 1:02d}"


seats = {}
for month, name, votes in wb["Constituency Votes"].iter_rows(min_row=2, max_col=3, values_only=True):
    if not month:
        continue
    no = ac.index(ALIASES.get(name, name)) + 1
    seats.setdefault(key(month), {})[no] = seats.get(key(month), {}).get(no, 0) + int(votes)

polls = {}
for row in wb["Featured Polls"].iter_rows(min_row=2, max_col=4, values_only=True):
    month, poll, option, votes = row
    if not month:
        continue
    polls.setdefault(POLLS[poll], {}).setdefault(key(month), {})[option.strip()] = int(votes)

out = [
    "// GENERATED by tools/import_external.py from",
    f"// {Path(sys.argv[1]).name}. Do not edit by hand.",
    "",
    "/// Votes collected outside VoteWala (Facebook) before VoteWala polls began.",
    "/// Always shown with the label [ExternalData.label].",
    "abstract final class ExternalData {",
    "  static const label = 'External Data from Facebook';",
    "  static const labelTe = 'Facebook నుండి సేకరించిన బయటి డేటా';",
    "",
    "  /// Featured poll id -> month key -> option (English name) -> votes.",
    "  static const featured = <String, Map<String, Map<String, int>>>{",
]
for pid, months in polls.items():
    out.append(f"    '{pid}': {{")
    for m, opts in sorted(months.items()):
        body = ", ".join(f"'{o}': {v}" for o, v in opts.items())
        out.append(f"      '{m}': {{{body}}},")
    out.append("    },")
out += ["  };", "", "  /// Month key -> assembly constituency number -> votes.", "  static const assembly = <String, Map<int, int>>{"]
for m, d in sorted(seats.items()):
    body = ", ".join(f"{no}: {v}" for no, v in sorted(d.items()))
    out.append(f"    '{m}': {{{body}}},")
out += ["  };", "}", ""]
Path("lib/data/external_data.dart").write_text("\n".join(out))
print("months", sorted(seats), "polls", {p: len(m) for p, m in polls.items()})
print("assembly totals", {m: sum(d.values()) for m, d in sorted(seats.items())})
