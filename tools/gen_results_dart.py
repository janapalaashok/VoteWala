"""Convert tools/data/results-2024.txt (from fetch_2024_results.py) into
lib/data/results_2024.dart and check it against the official seat tally."""
import collections
import json
import re
import sys
import urllib.parse

SRC, OUT = "tools/data/results-2024.txt", "lib/data/results_2024.dart"
PARTY = {"TDP": "tdp", "YSRCP": "ysrcp", "YCP": "ysrcp", "JSP": "jsp", "JnP": "jsp", "JNP": "jsp",
         "JSP ": "jsp", "BJP": "bjp", "INC": "inc"}

rows = collections.defaultdict(list)
images = {}
for line in open(SRC, encoding="utf-8"):
    kind, _, rest = line.rstrip("\n").partition("|")
    if kind == "ROW":
        k, t, data = rest.split("|", 2)
        rows[(k, int(t))].append(json.loads(data))
    elif kind == "IMG":
        d = json.loads(rest)
        images[d["title"]] = d["url"].split("?")[0]


def photo(cell):
    for href in cell["l"]:
        title = urllib.parse.unquote(href).replace("_", " ")
        if title in images:
            return images[title]
    return None


def num(s):
    return int(re.sub(r"[^\d]", "", s) or 0)


def parse(table, suffix):
    out = {}
    for r in table:
        idx = next((i for i, c in enumerate(r) if any(h.endswith(suffix) for h in c["l"])), None)
        if idx is None or idx == 0 or not r[idx - 1]["t"].isdigit():
            continue
        no = int(r[idx - 1]["t"])
        cells = [c for c in r[idx + 1:]]
        # Skip a turnout column (Lok Sabha) if present before the winner's name.
        if re.fullmatch(r"[\d.]+", cells[0]["t"]):
            cells = cells[1:]
        cells = [c for c in cells if c["t"] != ""]
        w, wp, wv, _, ru, rp, rv = cells[:7]
        out[no] = {
            "name": r[idx]["t"],
            "w": (w["t"], PARTY.get(wp["t"], "oth"), num(wv["t"]), photo(w), wp["t"]),
            "r": (ru["t"], PARTY.get(rp["t"], "oth"), num(rv["t"]), photo(ru), rp["t"]),
        }
    return out


mla = parse(rows[("assembly", 7)], "_Assembly_constituency")
mp = parse(rows[("loksabha", 10)], "_Lok_Sabha_constituency")
assert sorted(mla) == list(range(1, 176)), sorted(set(range(1, 176)) - set(mla))
assert sorted(mp) == list(range(1, 26)), sorted(set(range(1, 26)) - set(mp))

for label, data in (("MLA", mla), ("MP", mp)):
    tally = collections.Counter(v["w"][1] for v in data.values())
    unknown = {v["w"][4] for v in data.values() if v["w"][1] == "oth"} | {v["r"][4] for v in data.values() if v["r"][1] == "oth"}
    photos = sum(1 for v in data.values() if v["w"][3])
    print(label, dict(tally), "photos:", photos, "/", len(data), "other party labels:", unknown, file=sys.stderr)

assert collections.Counter(v["w"][1] for v in mla.values()) == {"tdp": 135, "jsp": 21, "bjp": 8, "ysrcp": 11}
assert collections.Counter(v["w"][1] for v in mp.values()) == {"tdp": 16, "ysrcp": 4, "bjp": 3, "jsp": 2}


def entry(c):
    name, party, votes, img, _ = c
    return f"Contestant2024({json.dumps(name, ensure_ascii=False)}, '{party}', {votes}, {json.dumps(img) if img else 'null'})"


def block(var, data):
    lines = [f"const {var} = <Result2024>["]
    for no in sorted(data):
        v = data[no]
        lines.append(f"  Result2024({entry(v['w'])}, {entry(v['r'])}), // {no} {v['name']}")
    lines.append("];")
    return "\n".join(lines)


open(OUT, "w", encoding="utf-8").write(f"""// GENERATED by tools/gen_results_dart.py from Wikipedia's 2024 result tables
// (source: Election Commission of India). Do not edit by hand.
// Photos: Wikimedia Commons thumbnails (null when no photo is available).

class Contestant2024 {{
  const Contestant2024(this.name, this.partyId, this.votes, this.photoUrl);

  final String name;
  final String partyId;
  final int votes;
  final String? photoUrl;
}}

class Result2024 {{
  const Result2024(this.winner, this.runnerUp);

  final Contestant2024 winner;
  final Contestant2024 runnerUp;

  int get margin => winner.votes - runnerUp.votes;
}}

/// Assembly results, index = constituency number - 1.
{block('assembly2024', mla)}

/// Lok Sabha results, index = constituency number - 1.
{block('loksabha2024', mp)}
""")
# Name check against the app's constituency list.
names = [v["name"] for _, v in sorted(mla.items())]
print("\n".join(f"{i+1}: {n}" for i, n in enumerate(names)), file=open("/dev/stdout", "w"))
